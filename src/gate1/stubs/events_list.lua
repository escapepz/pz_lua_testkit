local function build(names)
    local seen = {}
    local out = {}
    for _, n in ipairs(names) do
        if type(n) == "string" and n ~= "" and not seen[n] then
            seen[n] = true
            out[#out + 1] = n
        end
    end
    table.sort(out)
    return out
end
return {
    events = build(event_names),
    hooks = build(hook_names),
}
